using System.Collections.Generic;
using System.Linq;
using System.Text;

namespace ShellIcons.Generator.Xaml;

/* Emits the parts every XAML target shares: IconName, IconData, IconInfo/IconCatalog and the typed
   controls. Only the namespace differs, so MAUI and Avalonia get the same names and behavior. */
internal static class CatalogEmitter
{
    public static string Enum(string ns, XamlIcon[] icons)
    {
        var sb = Header();
        sb.AppendLine($"namespace {ns};");
        sb.AppendLine();
        sb.AppendLine("/// <summary>Every icon in the ShellIcons catalog. PascalCase of the Lucide file name (<c>chevron-right</c> → <c>ChevronRight</c>).</summary>");
        sb.AppendLine("public enum IconName");
        sb.AppendLine("{");
        sb.AppendLine("    /// <summary>No icon. The <c>Icon</c> control renders nothing.</summary>");
        sb.AppendLine("    None = 0,");
        for (var i = 0; i < icons.Length; i++)
        {
            sb.AppendLine($"    /// <summary><c>{icons[i].Kebab}</c> ({icons[i].Pack}).</summary>");
            sb.AppendLine($"    {icons[i].Pascal} = {i + 1},");
        }
        sb.AppendLine("}");
        return sb.ToString();
    }

    public static string Data(string ns, XamlIcon[] icons)
    {
        var sb = Header();
        sb.AppendLine($"namespace {ns};");
        sb.AppendLine();
        sb.AppendLine("// Path data for the Icon dispatcher. Referencing it keeps the whole catalog.");
        sb.AppendLine("internal static class IconData");
        sb.AppendLine("{");
        sb.AppendLine("    public static (string Stroke, string? Fill) Get(IconName name) => name switch");
        sb.AppendLine("    {");
        foreach (var icon in icons)
            sb.AppendLine($"        IconName.{icon.Pascal} => ({Literal(icon.Shapes.StrokeData)}, {LiteralOrNull(icon.Shapes.FillData)}),");
        sb.AppendLine("        _ => (string.Empty, null),");
        sb.AppendLine("    };");
        sb.AppendLine("}");
        return sb.ToString();
    }

    public static string Catalog(string ns, XamlIcon[] icons)
    {
        var cases = new StringBuilder();
        foreach (var icon in icons)
        {
            cases.Append($"        IconName.{icon.Pascal} => new IconInfo(IconName.{icon.Pascal}, {Literal(icon.Kebab)}, {Literal(icon.Pack)}, ");
            cases.Append(Array(icon.Meta.Tags)).Append(", ").Append(Array(icon.Meta.Categories)).Append(", ").Append(Array(icon.Meta.Aliases));
            cases.AppendLine("),");
        }

        return $$"""
            // <auto-generated/>
            #nullable enable

            using System;
            using System.Collections.Generic;
            using System.Linq;

            namespace {{ns}};

            /// <summary>Metadata for one icon, from its Lucide (or custom) JSON sidecar.</summary>
            /// <param name="Name">The enum value.</param>
            /// <param name="Id">Kebab-case catalog id, e.g. <c>chevron-right</c>.</param>
            /// <param name="Source"><c>lucide</c> or <c>custom</c>.</param>
            /// <param name="Tags">Search keywords.</param>
            /// <param name="Categories">Lucide categories.</param>
            /// <param name="Aliases">Former or alternative ids, e.g. <c>home</c> for <c>house</c>.</param>
            public sealed record IconInfo(
                IconName Name,
                string Id,
                string Source,
                IReadOnlyList<string> Tags,
                IReadOnlyList<string> Categories,
                IReadOnlyList<string> Aliases);

            /// <summary>Maps ids, names and Lucide aliases to <see cref="IconName"/>, with tags and search.</summary>
            public static class IconCatalog
            {
                /// <summary>Number of icons in the catalog (excluding <see cref="IconName.None"/>).</summary>
                public const int Count = {{icons.Length}};

                private static readonly Lazy<IReadOnlyList<IconInfo>> AllLazy = new(() =>
                    Enum.GetValues<IconName>()
                        .Where(n => n != IconName.None)
                        .Select(n => Create(n)!)
                        .ToArray());

                private static readonly Lazy<Dictionary<string, IconName>> Lookup = new(BuildLookup);

                /// <summary>Every icon, in catalog order.</summary>
                public static IReadOnlyList<IconInfo> All => AllLazy.Value;

                /// <summary>Metadata for <paramref name="name"/>.</summary>
                /// <exception cref="ArgumentOutOfRangeException"><paramref name="name"/> is <see cref="IconName.None"/> or undefined.</exception>
                public static IconInfo Get(IconName name) =>
                    Create(name) ?? throw new ArgumentOutOfRangeException(nameof(name), name, "Not an icon in the catalog.");

                /// <summary>Resolves <c>chevron-right</c>, <c>ChevronRight</c> or an alias like <c>home</c> (→ <c>House</c>). Case-insensitive.</summary>
                public static bool TryParse(string? value, out IconName name)
                {
                    name = IconName.None;
                    if (string.IsNullOrWhiteSpace(value)) return false;
                    return Lookup.Value.TryGetValue(value.Trim(), out name);
                }

                /// <summary>Icons whose id, alias, tag or category contains <paramref name="query"/> (case-insensitive). Id matches first.</summary>
                public static IEnumerable<IconInfo> Search(string query)
                {
                    if (string.IsNullOrWhiteSpace(query)) return All;
                    var q = query.Trim();

                    return All
                        .Select(i => (Info: i, Rank: Rank(i, q)))
                        .Where(x => x.Rank >= 0)
                        .OrderBy(x => x.Rank)
                        .Select(x => x.Info);
                }

                private static int Rank(IconInfo info, string q)
                {
                    if (info.Id.Contains(q, StringComparison.OrdinalIgnoreCase)) return 0;
                    if (info.Aliases.Any(a => a.Contains(q, StringComparison.OrdinalIgnoreCase))) return 1;
                    if (info.Tags.Any(t => t.Contains(q, StringComparison.OrdinalIgnoreCase))) return 2;
                    if (info.Categories.Any(c => c.Contains(q, StringComparison.OrdinalIgnoreCase))) return 3;
                    return -1;
                }

                private static Dictionary<string, IconName> BuildLookup()
                {
                    var map = new Dictionary<string, IconName>(StringComparer.OrdinalIgnoreCase);

                    // Canonical names first so an alias can never shadow a real icon id.
                    foreach (var info in All)
                    {
                        map[info.Id] = info.Name;
                        map[info.Name.ToString()] = info.Name;
                    }
                    foreach (var info in All)
                    {
                        foreach (var alias in info.Aliases)
                            map.TryAdd(alias, info.Name);
                    }

                    return map;
                }

                private static IconInfo? Create(IconName name) => name switch
                {
            {{cases}}        _ => null,
                };
            }
            """;
    }

    public static string TypedControl(string ns, XamlIcon icon)
    {
        var sb = Header();
        sb.AppendLine($"namespace {ns}.Icons;");
        sb.AppendLine();
        sb.AppendLine($"/// <summary>Icon <c>{icon.Kebab}</c> ({icon.Pack}). Carries its own path data, so unused icons are trimmed.</summary>");
        sb.AppendLine($"public sealed class {icon.Pascal} : global::{ns}.IconView");
        sb.AppendLine("{");
        sb.AppendLine($"    /// <summary>Creates the <c>{icon.Kebab}</c> icon.</summary>");
        sb.AppendLine($"    public {icon.Pascal}() : base(global::{ns}.IconName.{icon.Pascal}, {Literal(icon.Shapes.StrokeData)}, {LiteralOrNull(icon.Shapes.FillData)}) {{ }}");
        sb.AppendLine("}");
        return sb.ToString();
    }

    private static StringBuilder Header()
    {
        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine("#nullable enable");
        sb.AppendLine();
        return sb;
    }

    private static string Array(IReadOnlyList<string> values) =>
        values.Count == 0
            ? "global::System.Array.Empty<string>()"
            : "new[] { " + string.Join(", ", values.Select(Literal)) + " }";

    private static string LiteralOrNull(string? value) => value is null ? "null" : Literal(value);

    private static string Literal(string value)
    {
        var sb = new StringBuilder(value.Length + 2);
        sb.Append('"');
        foreach (var c in value)
        {
            switch (c)
            {
                case '"': sb.Append("\\\""); break;
                case '\\': sb.Append("\\\\"); break;
                case '\n': sb.Append("\\n"); break;
                case '\r': sb.Append("\\r"); break;
                case '\t': sb.Append("\\t"); break;
                default:
                    if (c < ' ') sb.Append("\\u").Append(((int)c).ToString("x4"));
                    else sb.Append(c);
                    break;
            }
        }
        sb.Append('"');
        return sb.ToString();
    }
}
