using System.Collections.Generic;
using System.Linq;
using System.Text;
using ShellIcons.Generator.Xaml;

namespace ShellIcons.Generator;

/* Emits ShellIcons.IconCatalog: every icon's id, component name and sidecar metadata, with lookup by id,
   name or former name, and search. Metadata only; it doesn't reference the icon components. */
internal static class BlazorCatalogEmitter
{
    public static string Emit(IconDefinition[] icons, IReadOnlyDictionary<string, IconMetadata> meta, IReadOnlyList<IconAlias> aliases)
    {
        var entries = new StringBuilder();
        foreach (var icon in icons)
        {
            var m = meta.TryGetValue(icon.KebabName, out var found) ? found : IconMetadata.Empty;
            entries.Append($"            new IconInfo({Literal(icon.KebabName)}, {Literal(icon.PascalName)}, {Literal(icon.SourcePack)}, ");
            entries.Append(Array(m.Tags)).Append(", ").Append(Array(m.Categories)).Append(", ").Append(Array(m.Aliases));
            entries.AppendLine("),");
        }

        // C# names of former names (Trash2) also resolve; their kebab ids are already in each icon's Aliases.
        var aliasNames = new StringBuilder();
        foreach (var a in aliases)
            aliasNames.AppendLine($"        [{Literal(a.Pascal)}] = {Literal(a.TargetKebab)},");

        return $$"""
            // <auto-generated/>
            #nullable enable

            using System;
            using System.Collections.Generic;
            using System.Linq;

            namespace ShellIcons;

            /// <summary>Metadata for one icon, from its Lucide (or custom) JSON sidecar.</summary>
            /// <param name="Id">Kebab-case id, as <c>&lt;ShellIcon Name="…" /&gt;</c> takes it: <c>chevron-right</c>.</param>
            /// <param name="Name">Component name: <c>ChevronRight</c> (<c>&lt;ChevronRightIcon /&gt;</c>, <c>Icon.ChevronRight()</c>).</param>
            /// <param name="Source"><c>lucide</c> or <c>custom</c>.</param>
            /// <param name="Tags">Search keywords.</param>
            /// <param name="Categories">Lucide categories.</param>
            /// <param name="Aliases">Former or alternative ids, e.g. <c>trash-2</c> for <c>trash</c>.</param>
            public sealed record IconInfo(
                string Id,
                string Name,
                string Source,
                IReadOnlyList<string> Tags,
                IReadOnlyList<string> Categories,
                IReadOnlyList<string> Aliases);

            /// <summary>
            /// Every icon with its tags, categories and former names, for icon pickers, search and tools.
            /// Holds metadata only, so using it doesn't keep the icons themselves in a trimmed app.
            /// </summary>
            public static class IconCatalog
            {
                /// <summary>Number of icons in the catalog.</summary>
                public const int Count = {{icons.Length}};

                private static readonly Lazy<IReadOnlyList<IconInfo>> AllLazy = new(Build);
                private static readonly Lazy<(Dictionary<string, IconInfo> Exact, Dictionary<string, IconInfo> AnyCase)> Lookup = new(BuildLookup);

                private static readonly Dictionary<string, string> AliasNames = new(StringComparer.Ordinal)
                {
            {{aliasNames}}    };

                /// <summary>Every icon, ordered by id.</summary>
                public static IReadOnlyList<IconInfo> All => AllLazy.Value;

                /// <summary>
                /// Resolves an id (<c>chevron-right</c>), a component name (<c>ChevronRight</c>) or a former name
                /// (<c>trash-2</c>, <c>Trash2</c>) to the icon's current id. Exact case first, then any case.
                /// </summary>
                public static bool TryParse(string? value, out string id)
                {
                    id = string.Empty;
                    if (!TryGet(value, out var info)) return false;
                    id = info.Id;
                    return true;
                }

                /// <summary>Like <see cref="TryParse"/>, returning the icon's metadata.</summary>
                public static bool TryGet(string? value, [System.Diagnostics.CodeAnalysis.NotNullWhen(true)] out IconInfo? info)
                {
                    info = null;
                    if (string.IsNullOrWhiteSpace(value)) return false;

                    var key = value.Trim();
                    return Lookup.Value.Exact.TryGetValue(key, out info) || Lookup.Value.AnyCase.TryGetValue(key, out info);
                }

                /// <summary>Metadata for an id, component name or former name.</summary>
                /// <exception cref="ArgumentException"><paramref name="value"/> isn't an icon in the catalog.</exception>
                public static IconInfo Get(string value) =>
                    TryGet(value, out var info) ? info : throw new ArgumentException($"'{value}' is not an icon in the catalog.", nameof(value));

                /// <summary>Icons whose id, alias, tag or category contains <paramref name="query"/> (case-insensitive). Id matches first.</summary>
                public static IEnumerable<IconInfo> Search(string? query)
                {
                    if (string.IsNullOrWhiteSpace(query)) return All;
                    var q = query.Trim();

                    return All
                        .Select(i => (Info: i, Rank: Rank(i, q)))
                        .Where(x => x.Rank >= 0)
                        .OrderBy(x => x.Rank)
                        .Select(x => x.Info);
                }

                /// <summary>The catalog as JSON (<c>[{ "id", "name", "source", "tags", "categories", "aliases" }]</c>), to serve as an <c>icons.json</c> file.</summary>
                public static string ToJson() =>
                    System.Text.Json.JsonSerializer.Serialize(All, new System.Text.Json.JsonSerializerOptions
                    {
                        PropertyNamingPolicy = System.Text.Json.JsonNamingPolicy.CamelCase,
                    });

                private static int Rank(IconInfo info, string q)
                {
                    if (info.Id.Contains(q, StringComparison.OrdinalIgnoreCase)) return 0;
                    if (info.Aliases.Any(a => a.Contains(q, StringComparison.OrdinalIgnoreCase))) return 1;
                    if (info.Tags.Any(t => t.Contains(q, StringComparison.OrdinalIgnoreCase))) return 2;
                    if (info.Categories.Any(c => c.Contains(q, StringComparison.OrdinalIgnoreCase))) return 3;
                    return -1;
                }

                private static (Dictionary<string, IconInfo>, Dictionary<string, IconInfo>) BuildLookup()
                {
                    var exact = new Dictionary<string, IconInfo>(StringComparer.Ordinal);
                    var anyCase = new Dictionary<string, IconInfo>(StringComparer.OrdinalIgnoreCase);
                    var byId = All.ToDictionary(i => i.Id, StringComparer.Ordinal);

                    void Add(string key, IconInfo info)
                    {
                        exact.TryAdd(key, info);
                        anyCase.TryAdd(key, info);
                    }

                    // Current names first so a former name can never shadow a real icon.
                    foreach (var info in All)
                    {
                        Add(info.Id, info);
                        Add(info.Name, info);
                    }
                    foreach (var info in All)
                    {
                        foreach (var alias in info.Aliases)
                            Add(alias, info);
                    }
                    foreach (var pair in AliasNames)
                        Add(pair.Key, byId[pair.Value]);

                    return (exact, anyCase);
                }

                private static IReadOnlyList<IconInfo> Build() => new IconInfo[]
                {
            {{entries}}        };
            }
            """;
    }

    private static string Array(IReadOnlyList<string> values) =>
        values.Count == 0
            ? "global::System.Array.Empty<string>()"
            : "new[] { " + string.Join(", ", values.Select(Literal)) + " }";

    private static string Literal(string value)
    {
        var sb = new StringBuilder(value.Length + 2);
        sb.Append('"');
        foreach (var c in value)
        {
            switch (c)
            {
                case '"': sb.Append("\\\""); break;
                case '\\': sb.Append("\\\\"); break;
                case '\n': sb.Append("\\n"); break;
                case '\r': sb.Append("\\r"); break;
                case '\t': sb.Append("\\t"); break;
                default:
                    if (c < ' ') sb.Append("\\u").Append(((int)c).ToString("x4"));
                    else sb.Append(c);
                    break;
            }
        }
        sb.Append('"');
        return sb.ToString();
    }
}
